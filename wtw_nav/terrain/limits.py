class TerrainNotSupported(Exception):
    """LLC 능력 밖의 지형을 만들려 했다."""


def validate(kind: str, value: float) -> float:
    """지형 파라미터를 관문에 통과시킨다. 실패하면 예외.

    지형 생성기와 커리큘럼은 **반드시** 이걸 거쳐야 한다. 조용히 잘라내지 않고
    예외를 던지는 이유: 커리큘럼이 상한을 넘겨도 학습은 계속 돌기 때문에,
    잘라내면 우리는 정책이 왜 정체하는지 영원히 모른다.
    """
    if kind in REMOVED:
        raise TerrainNotSupported(f"'{kind}'는 스코프에서 제외됐습니다.\n  {REMOVED[kind]}")
    if kind not in LIMITS:
        raise TerrainNotSupported(f"알 수 없는 지형 '{kind}'. 가능: {sorted(LIMITS)}")
    lim = LIMITS[kind]
    if not lim.measured:
        raise TerrainNotSupported(
            f"'{kind}'는 아직 실측되지 않아 쓸 수 없습니다.\n  {lim.source}")
    if not lim.ok(value):
        rel = "이하" if lim.direction == "max" else "이상"
        raise TerrainNotSupported(
            f"'{kind}' {value}{lim.unit}는 능력 밖입니다 "
            f"(사용 가능 {lim.usable:.3f}{lim.unit} {rel}, "
            f"실측 {lim.value}{lim.unit}, 여유 ×{lim.margin}).\n  {lim.source}")
    return value


def usable_range(kind: str) -> tuple[float, float] | None:
    """커리큘럼이 샘플링해도 되는 구간. 미측정이면 `None`."""
    lim = LIMITS.get(kind)
    if lim is None or not lim.measured:
        return None
    u = lim.usable
    return (0.0, u) if lim.direction == "max" else (u, u * 3.0)


